#!/usr/bin/env python3
"""Заголовки утверждений: проверка того, что читается человеком, а не только автором.

16-10-2026 владелец читал разбор StructZO и остановился на разделе утверждений:
«описание утверждений читать нельзя… эффективная размерность оценки падает с М на Н до М на
Р, не до нуля — когда она падает, при каких условиях?.. Средний выигрыш над лучшими
зоометодами до 8.7% — и что это значит?». Заголовок там кончался на середине фразы, нёс
обозначения статьи вместо слов, а процент был без базы — и всё это было не одной страницей:
из 700 разборов с утверждениями изъяны нашлись на 173.

Правила в `skills/paper-ingest/references/canon-ingest.md` это уже запрещали, но проверять их
было нечем, поэтому проверка здесь. Четыре класса, и каждый — буквальный, без суждения:

- **обрыв**: заголовок кончается запятой, предлогом или союзом, то есть его не дописали;
- **формула несёт утверждение**: в заголовке команда LaTeX или два и больше обозначений,
  а человек со стороны читает заголовок первым и расшифровки рядом не имеет;
- **процент без базы**: процент назван, а база (от чего он) — нет;
- **адрес вместо смысла**: в заголовке номер теоремы, таблицы или рисунка;
- **спор с собой**: в теле осталась правка на ходу («— нет, здесь всё же выше»).

    paper_claims_lint.py <файл или папка>...

Код возврата 1, если хоть что-то нашлось: так проверку можно поставить в ворота.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HEAD = re.compile(r"(?m)^### Утверждение\s*(\d+)\s*—\s*(.+?)\s*$")
SECTION = re.compile(r"(?ms)^## Что статья утверждает\n(.*?)(?=^## (?!#)|\Z)")
#: Заголовок кончается тем, после чего обязано идти продолжение.
#: «по отдельности» здесь когда-то стояло: с него начался весь разбор, потому что заголовок
#: «необходимы одновременно, по отдельности» был не дописан. Но «лучше, чем каждая из частей
#: по отдельности» — законченная фраза, и 16-10-2026 проверка поймала две такие. Обрыв
#: опознаётся висящим союзом или предлогом, а не этими словами.
CUT = re.compile(r"(,|\bи|\bили|\bно|\bпри|\bдля|\bчем|\bчто|\bкак)\s*$", re.I)
#: Команда LaTeX в заголовке: её читают как формулу, а не как фразу.
#: Признак формулы — ОТНОШЕНИЕ или конструкция, а не греческая буква: «порядок
#: $\epsilon^{-(4+a)}$» и «параметр $\theta$» это имена величин внутри нормальной фразы, и
#: канон их разрешает. Буквы 16-10-2026 убраны из списка: они дали двенадцать срабатываний
#: подряд на связных заголовках, а настоящую формулу («закон $\hat N = D/(\eta A\|g_0\|_1)$»)
#: выдаёт дробь или равенство в длинной вставке: `$D=32$` и `$K=4$` это настройка опыта,
#: а `$\hat N = D/(\eta A\|g_0\|_1)$` — закон, который и есть утверждение.
MATH_CMD = re.compile(r"\\(operatorname|mathbb|mathcal|frac|sum|prod|int|nabla|le|ge|ll|gg"
                      r"|approx|neq|sim|propto|hat|bar|tilde|widehat|langle)\b|\\\|")
#: Вставка из одних цифр — это значение, а не обозначение: `$6.6\times10^{-6}$` человек
#: читает как число и спотыкаться ему не на чем.
ONLY_NUMBER = re.compile(r"\A[\d\s.,%^{}()+\-/]*(\\times|\\cdot|10|\^)?[\d\s.,%^{}()+\-/]*\Z")


def math_spans(title: str) -> list[str]:
    """Вставки `$…$` в заголовке. Считаются по чётности долларов, а не поиском пары.

    Регулярка `\$([^$]{5,})\$` склеивает два соседних обозначения в одно фантомное: закрывающий
    доллар первого становится открывающим для второго, и фраза «заморозить матрицу $A$ и
    обучать $k$ элементов» выглядит как формула на сорок знаков. 16-10-2026 это дало десяток
    ложных срабатываний подряд.
    """
    parts = title.split("$")
    return [one for one in parts[1::2]
            if len(one) >= 5 and not ONLY_NUMBER.fullmatch(one.replace("\\times", ""))]
#: Ловится не всякий процент, а обещание величины без сравнения: «выигрыш до 8.7%». Процент
#: с названной базой («70.08% против 70.23% у SGD», «на 15% ниже его собственной», «словарь
#: короче на 90%») — нормальная фраза, и 16-10-2026 именно такие дали сто ложных
#: срабатываний на первой, более грубой проверке.
PCT = re.compile(r"\b(?:до|около|примерно|в среднем|вплоть до)\s*\d+(?:[.,]\d+)?\s*%")
#: База процента: от чего он считается и чего именно. Пункт — уже абсолютная разница.
BASE = re.compile(r"\bот\s|\bпункт|\bчем\b|\bпротив\b|\bу\s+[`A-ZА-Я]|\bотносительно\b"
                  r"|\bниже\b|\bвыше\b|\bиз\s+\d|\bдол[июя]\b|\bвсех\b|\bбюджет"
                  r"|\bпараметр|\bнакладн|\bвремен|\bпамят|\bитераци|\bтокен|\bшаг|\bсвоего\b")
#: Заголовок, в который уложили весь разбор. Замер 16-10-2026 по 2266 заголовкам базы:
#: медиана 237 знаков, длиннее 400 — 229 заголовков, длиннее 500 — 64, самый длинный 771.
#: Порог поставлен по тому, где заголовок перестаёт читаться с одного взгляда, а не по вкусу:
#: за 400 знаками в нём уже два-три утверждения через точку с запятой, и место им в
#: «Смысл такой» строкой ниже.
TOO_LONG = 400
ADDRESS = re.compile(r"\b(Theorem|Lemma|Proposition|Corollary|Table|Figure|Теорем\w*|Лемм\w*|Таблиц\w*|Рисун\w*)\s*\d", re.I)
#: Спор с собой ловится ЗАПЯТОЙ, а не точкой: «— нет, здесь всё же выше» это брошенная
#: правка, а «Причинность доказана, новизна механизма — нет.» — обычный русский эллипсис, и
#: таких законных мест в библиотеке восемь на семь страниц.
#: Брошенная правка опознаётся не словом «нет», а тем, что идёт ЗА ним: автор возвращается
#: и переспоривает сам себя. «а какую — нет, и для Adam эта часть меньше» — обычная фраза,
#: «— нет, здесь StructZO всё же выше» — оставленный след редактирования.
FIGHT = re.compile(r"—\s*(?:нет|да),\s*(?:здесь|тут|на самом деле|всё же|все же|наоборот"
                   r"|правильнее|верно|выше|ниже)\b|прошу прощения|я ошибся")


def check(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8", errors="replace")
    block = SECTION.search(text)
    if block is None:
        return []
    found: list[str] = []
    for number, title in HEAD.findall(text):
        where = f"{path.name} · утверждение {number}"
        if CUT.search(title):
            found.append(f"{where}: обрыв — заголовок кончается на середине фразы: «{title}»")
        if MATH_CMD.search(title) or len(math_spans(title)) >= 2:
            found.append(f"{where}: формула несёт утверждение — обозначения вместо слов: «{title}»")
        if PCT.search(title) and not BASE.search(title):
            found.append(f"{where}: процент без базы — непонятно, процент от чего: «{title}»")
        if ADDRESS.search(title):
            found.append(f"{where}: адрес вместо смысла — номер теоремы или таблицы в заголовке: «{title}»")
        if len(title) > TOO_LONG:
            found.append(f"{where}: заголовок стал абзацем — {len(title)} знаков, "
                         f"читается не с одного взгляда: «{title[:90]}…»")
    for hit in FIGHT.finditer(block.group(1)):
        start = max(0, hit.start() - 90)
        found.append(f"{path.name}: спор с собой — осталась правка на ходу: "
                     f"«…{block.group(1)[start:hit.end()]}»")
    return found


def main(argv: list[str]) -> int:
    paths: list[Path] = []
    for one in argv:
        root = Path(one)
        paths.extend(sorted(root.glob("**/*.md")) if root.is_dir() else [root])
    trouble = 0
    pages = 0
    for path in paths:
        if path.name == "README.md":
            continue
        said = check(path)
        if said:
            pages += 1
            trouble += len(said)
            for one in said:
                print(one)
    print(f"\nстраниц с изъянами: {pages}, изъянов: {trouble}")
    return 1 if trouble else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
