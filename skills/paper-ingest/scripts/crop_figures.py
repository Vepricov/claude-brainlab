#!/usr/bin/env python3
"""Вырезать рисунок из PDF по подписи и границам самой графики.

Зачем отдельно от `extract_pdf_figures.py --vector`: тот берёт полосу во всю
ширину страницы, и на двухколоночной вёрстке в кадр попадает соседняя колонка
текста. Здесь колонка определяется по самой подписи, а верхняя граница — по
объединению векторных примитивов и растров, которые лежат над ней в этой же
колонке. Нужно это для рисунков, нарисованных в TikZ: файла у них нет, и из
исходников arXiv они не извлекаются вовсе.

    crop_figures.py paper.pdf out_dir "Figure 1" "Figure 2"
"""
import re, sys, pathlib
import fitz

ОТСТУП = 4          # поля вокруг найденной области, в пунктах
DPI = 200


def подпись(page, номер, ожидаем=""):
    """Прямоугольник подписи «Figure N.» — именно подписи, а не ссылки и не описания.

    Две ловушки. Первая: `search_for` находит упоминание внутри абзаца, поэтому
    требуем, чтобы совпадение НАЧИНАЛО строку. Вторая: у 2609.38095 рядом с
    настоящей подписью стоит короткое описание для доступности, тоже с «Figure N.»
    в начале — на странице 10 таких пар две. Различаем по тексту подписи из
    исходника: `ожидаем` это его первые слова.
    """
    образец = re.compile(r"^Figure\s+" + str(номер) + r"\s*[.:]\s*(.*)")
    запасной = None
    for блок in page.get_text("dict")["blocks"]:
        if блок.get("type") != 0:
            continue
        for линия in блок["lines"]:
            текст = "".join(s["text"] for s in линия["spans"]).strip()
            m = образец.match(текст)
            if not m:
                continue
            if not ожидаем:
                return fitz.Rect(линия["bbox"])
            хвост = re.sub(r"\W+", "", m.group(1)).lower()
            ждём = re.sub(r"\W+", "", ожидаем).lower()[:len(хвост)] or "~"
            if хвост.startswith(ждём[:20]):
                return fitz.Rect(линия["bbox"])
            запасной = запасной or fitz.Rect(линия["bbox"])
    return None


def над_подписью(page, кап, зазор=28):
    """Границы рисунка над подписью.

    Порядок важен и выведен на ошибках. Ширину задаёт ТОЛЬКО графика: векторные
    примитивы и растры. Если позволить её задавать тексту, в кадр уезжает соседняя
    колонка статьи — так и вышло на Figure 2 у 2609.38095. Зато подписи осей и
    числа внутри рисунка тоже текст, поэтому их добавляем вторым проходом, и лишь
    те, что попадают в уже найденную ширину: без них отрезало шапку теплокарты.
    Вверх растём, пока разрыв между кусками меньше `зазор`, — абзац статьи отделён
    большим промежутком и не прилипает.
    """
    графика = [d["rect"] for d in page.get_drawings()
               if d["rect"].y1 <= кап.y0 + 2 and d["rect"].height > 0.5]
    for блок in page.get_text("dict")["blocks"]:
        r = fitz.Rect(блок["bbox"])
        if блок.get("type") == 1 and r.y1 <= кап.y0 + 2:
            графика.append(r)
    if not графика:
        return None

    графика.sort(key=lambda r: r.y1, reverse=True)
    область = fitz.Rect(графика[0])
    росло = True
    while росло:
        росло = False
        for r in графика:
            if r.y1 >= область.y0 - зазор and r.y0 <= область.y1 + зазор:
                новая = область | r
                if новая != область:
                    область, росло = новая, True

    # Второй проход: текст, который принадлежит рисунку. Отличаем от абзаца статьи
    # по двум признакам сразу — он узкий (подпись оси, число, заголовок панели) и
    # примыкает к графике вплотную. Колонка статьи широкая и отделена промежутком.
    росло = True
    while росло:
        росло = False
        for блок in page.get_text("dict")["blocks"]:
            if блок.get("type") != 0:
                continue
            r = fitz.Rect(блок["bbox"])
            if r.y1 > кап.y0 + 2 or r.width > 130:
                continue
            рядом_по_вертикали = r.y1 >= область.y0 - зазор and r.y0 <= область.y1 + зазор
            рядом_по_горизонтали = (r.x1 >= область.x0 - 40 and r.x0 <= область.x1 + 40)
            if рядом_по_вертикали and рядом_по_горизонтали:
                новая = область | r
                if новая != область:
                    область, росло = новая, True

    return fitz.Rect(max(0, область.x0 - ОТСТУП), max(0, область.y0 - ОТСТУП),
                     min(page.rect.width, область.x1 + ОТСТУП),
                     min(page.rect.height, кап.y0 - 2))


def main():
    pdf, вывод = sys.argv[1], pathlib.Path(sys.argv[2])
    вывод.mkdir(parents=True, exist_ok=True)
    # Аргумент вида `2=Comparison of 1SPSA`: номер и первые слова подписи из
    # исходника. Без второй половины подпись путается с описанием рядом.
    нужны = {}
    for арг in sys.argv[3:]:
        номер, _, ожидаем = арг.partition("=")
        нужны[re.sub(r"\D+", "", номер)] = ожидаем
    doc = fitz.open(pdf)
    сделано = {}
    for стр in doc:
        for номер in нужны:
            if номер in сделано:
                continue
            кап = подпись(стр, номер, нужны[номер])
            if not кап:
                continue
            обл = над_подписью(стр, кап)
            if not обл or обл.height < 40:
                continue
            пикс = стр.get_pixmap(clip=обл, dpi=DPI)
            путь = вывод / f"figure_{номер}.png"
            пикс.save(путь)
            сделано[номер] = (стр.number + 1, round(обл.width), round(обл.height))
            print(f"Figure {номер}: стр. {стр.number + 1}, {пикс.width}x{пикс.height} -> {путь.name}")
    for номер in нужны:
        if номер not in сделано:
            print(f"Figure {номер}: не нашёлся")


if __name__ == "__main__":
    main()
